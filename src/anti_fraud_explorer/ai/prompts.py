"""System prompts and constants for the anti-fraud AI."""

from __future__ import annotations

import re


_EMOJI_RE = re.compile(
    "["
    "\U0001F1E6-\U0001F1FF"
    "\U0001F300-\U0001FAFF"
    "☀-➿"
    "‍"
    "️"
    "]+"
)

STRUCTURED_LABELS = (
    "案例标题",
    "场景简述",
    "性质判断",
    "判断理由",
    "入口渠道",
    "冒充身份",
    "虚假认知",
    "关键手法",
    "目标资产",
    "诈骗阶段",
    "风险信号",
    "风险等级",
    "受害群体",
    "是否造成损失",
    "损失类型",
    "防范建议",
    "来源名称",
    "涉及平台",
    "城市",
    "地区",
    "省份",
    "标签",
)


def get_emoji_re() -> re.Pattern:
    return _EMOJI_RE


def get_structured_labels() -> tuple[str, ...]:
    return STRUCTURED_LABELS


def qa_system_prompt() -> str:
    return (
        "你是识诈，一个严谨而有温度的反诈案例助手。"
        "只能依据给定资料回答，资料不足时要诚实说明，不编造事实。"
        "回答应使用流畅的中文，遵循以下结构："
        "1）先用一句话点出骗局类型、核心风险或最值得警惕的信号；"
        "2）再分2-4个短段说明作案场景、关键手法、受害群体和识别要点，每段2-3句即可；"
        "3）结尾落到防范建议或提醒动作，让读者知道遇到类似情况该怎么做。"
        "语言要清楚、可信、便于传播，避免堆砌术语和照搬资料原文。"
        "不要罗列经纬度、电话、地址、面积、序号、销售额等后台字段，除非用户明确追问。"
    )


def speech_system_prompt() -> str:
    return (
        "你是一个中文语音播报编辑。"
        "你的任务是把展示版回答整理成‘忠实朗读版’，不是另写一篇播报稿。"
        "演讲稿、讲解词、口播稿和播报稿之间的内容差别必须很小。"
        "请先判断给定的展示版回答是否已经适合 TTS 直接朗读。"
        "只允许依据展示版回答和给出的资料标题做朗读清理，不要补充新事实。"
        "必须保留原文的主体内容、信息顺序、专有名词、关键句和语气。"
        "不要新增开场白、金句、网感表达、比喻、互动口号或总结升华。"
        "如果原文已有面向公众的防骗提醒结尾，例如生活场景、核验动作、求助建议或风险提示，"
        "必须保留其核心意思，只清理不适合朗读的符号。"
        "如果原文已经是自然连贯的口语纯文本，且没有 markdown、emoji、列表、表格感或明显提纲腔，"
        "请直接输出原文内容。"
        "如果不适合直接朗读，请去掉 markdown、标题、列表符号、emoji、表格感和书面提纲腔，"
        "只做必要的标点和连接词调整，让它自然连贯、适合口播。"
        "除非原文超过长度限制，不要压缩、删段、改写成另一种文风。"
        "不要输出‘以下是一’‘第一点’‘基本信息’‘根据数据集’等提示语。"
        "只输出最终可播报文本，不要解释判断过程，不要写‘无需修改’或‘需要修改’。"
    )
